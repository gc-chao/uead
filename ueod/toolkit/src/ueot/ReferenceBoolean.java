
package ueot;

public final class ReferenceBoolean extends Reference<Boolean>
{
    /**
     * Create reference boolean type.
     */
    public ReferenceBoolean()
    {
        super();
    }

    /**
     * Create reference boolean type with specified initial value.
     * @param value the value
     */
    public ReferenceBoolean(Boolean value)
    {
        super(value);
    }
}