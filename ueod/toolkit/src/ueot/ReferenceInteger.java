
package ueot;

public final class ReferenceInteger extends Reference<Integer>
{
    /**
     * Create reference integer type.
     */
    public ReferenceInteger()
    {
        super();
    }

    /**
     * Create reference integer type with specified initial value.
     * @param value the value
     */
    public ReferenceInteger(Integer value)
    {
        super(value);
    }
}